-- =====================================================================
--  توليد رابط تفعيل حساب مدير النظام
--
--  شغّله في Supabase SQL Editor بعد نشر الواجهة.
--
--  ⚠️  قبل التشغيل: غيّر قيمة عنوان الواجهة في السطر الأول من الاستعلام
--      إلى رابطك الحقيقي من Vercel.
--
--  النتيجة تحتوي عمود «الرابط الكامل» — افتحه في المتصفح مباشرة.
--
--  الرابط صالح 24 ساعة ويُستخدم مرة واحدة فقط. الرمز نفسه لا يُخزَّن
--  في قاعدة البيانات — يُخزَّن هاش SHA-256 فقط. تشغيل هذا الملف مرة
--  أخرى يُبطل الرابط السابق تلقائيًا.
-- =====================================================================
with إعدادات as (
  select
    'https://ضع-رابطك-هنا.vercel.app' as عنوان_الواجهة,  -- ← غيّر هذا
    'محمد صالح باعمر'                 as الاسم,
    '0559847714'                      as رقم_الجوال,
    'CN-06'                           as كود_الموقع,      -- الإدارة المركزية
    24                                as ساعات_الصلاحية
),
رمز as (
  select encode(gen_random_bytes(32), 'hex') as raw_token, * from إعدادات
)
select
  rtrim(عنوان_الواجهة, '/') || '/activate/?token=' || raw_token
    as "الرابط الكامل — افتحه الآن",
  app.create_activation_token(
    encode(digest(raw_token, 'sha256'), 'hex'),
    الاسم, رقم_الجوال, 'super_admin', كود_الموقع, ساعات_الصلاحية
  ) as "معرّف الرمز",
  (now() + make_interval(hours => ساعات_الصلاحية)) as "ينتهي في"
from رمز;
