-- =====================================================================
-- توليد رابط تفعيل مدير النظام من داخل Supabase SQL Editor
-- بديل عن scripts/create-activation-link.mjs — لا يحتاج أدوات محلية
-- ولا يتطلب وجود مفتاح الخدمة على جهازك.
--
-- الطريقة:
--   1) عدّل الاسم ورقم الجوال أدناه إن لزم.
--   2) نفّذ الاستعلام مرة واحدة.
--   3) انسخ قيمة TOKEN من النتيجة فورًا وركّبها في الرابط:
--        https://<عنوان-واجهتك>/activate/?token=<TOKEN>
--
-- تنبيه: الرمز يظهر في سجل SQL Editor. صلاحيته 24 ساعة ولمرة واحدة،
-- ويُبطَل تلقائيًا بمجرد استخدامه أو بإنشاء رمز جديد لنفس الرقم.
-- بعد التفعيل يمكنك مسح تاريخ الاستعلامات من المحرر.
-- =====================================================================

with gen as (
  select encode(gen_random_bytes(32), 'hex') as raw_token
)
select
  raw_token as "TOKEN — انسخه الآن",
  app.create_activation_token(
    encode(digest(raw_token, 'sha256'), 'hex'),  -- الهاش وحده يُخزَّن
    'محمد صالح باعمر',        -- الاسم
    '0559847714',             -- رقم الجوال
    'super_admin',            -- الدور
    'CN-06',                  -- كود الموقع: الإدارة المركزية
    24                        -- مدة الصلاحية بالساعات
  ) as "معرّف الرمز",
  (now() + interval '24 hours') as "ينتهي في"
from gen;
